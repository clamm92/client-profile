import { z } from "zod/v4";

export const LIMITS = {
  client_name: 160,
  intro_words: 60,
  intro_chars: 500,
  bullet_chars: 120,
  heading_chars: 60,
  cell_chars: 160,
  kv_value_chars: 200,
  max_sections: 8,
  max_items: 6,
  max_kv: 8,
  max_rows: 8,
  max_cols: 4,
  max_links_each: 3,
  label_chars: 24,
};

/* Visible-content rules from the product requirements. */
const FORBIDDEN_TAGS = /\[(FACT|INFERRED|STATED|USER|ASSUMPTION)\]/i;
const FORBIDDEN_PHRASES = [
  [/confidence/i, "confidence wording"],
  [/executive\s+briefing/i, "'Executive briefing' wording"],
  [/client\s+profile\s*$/i, "a 'Client Profile' banner"],
  [/\bAI[- ]generated\b|generated by (an )?AI|language model/i, "an AI-generated disclaimer"],
  [/public[- ]records?\s+disclaimer|based on publicly available information|public information only/i, "a public-records disclaimer"],
  [/\b(prepared|generated|compiled|as of)\s+(on\s+)?(date|today)\b/i, "a preparation date"],
  [/\bprepared\s+(on|:)/i, "a preparation date"],
  [/\bno data\b|\bnot available\b|\bnot verified\b|\bnone found\b|\bn\/a\b|\bnot disclosed\b|\bTBD\b|\bTODO\b|\bplaceholder\b|\blorem ipsum\b/i, "missing-data or placeholder wording"],
  [/\b(retrieval|lookup|request)\s+(failed|error)\b|\btool error\b|\baccess (denied|problem)\b|\bunable to (retrieve|access|fetch)\b|\bcould not (retrieve|access|fetch)\b|\brate[- ]limit/i, "tool-error or retrieval-failure wording"],
  [/https?:\/\/|\bwww\.[a-z0-9-]+\.[a-z]{2,}/i, "a raw URL"],
  [/^\s*(sources?(\s+and\s+confidence)?|references|citations|bibliography)\s*:?\s*$/i, "a standalone sources section"],
  [/risks?\s+and\s+conversation\s+starters?|conversation\s+starters?|^\s*red\s+flags?\s*$/i, "a risks/conversation-starters section"],
  [/^\s*(methodology|research gaps?|gaps|limitations)\s*$/i, "a methodology/gaps section"],
];
const PLACEHOLDER_ONLY = /^\s*([-–—_.…?]+|null|undefined|nan|n\/a|none|tbd|todo|\s)*$/i;
const MD_CONTROL = /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/;
const BIDI = /[\u202a-\u202e\u2066-\u2069]/;

export function visibleProblem(text, { allowName = false } = {}) {
  if (typeof text !== "string") return "not text";
  if (PLACEHOLDER_ONLY.test(text)) return "empty or placeholder text";
  if (MD_CONTROL.test(text)) return "control characters";
  if (BIDI.test(text)) return "bidirectional override characters";
  if (FORBIDDEN_TAGS.test(text)) return "a visible category label";
  if (/\[(?:FACT|INFERRED|STATED|USER|ASSUMPTION)\b/i.test(text)) return "a visible category label";
  for (const [re, label] of FORBIDDEN_PHRASES) {
    if (allowName && label === "'Executive briefing' wording") continue;
    if (re.test(text)) return label;
  }
  return null;
}

const linkSchema = z.strictObject({
  label: z.string().min(1).max(LIMITS.label_chars),
  url: z.string().url().max(2048),
});
const links = z.array(linkSchema).max(LIMITS.max_links_each).optional();

const section = z.strictObject({
  id: z.string().regex(/^[a-z][a-z0-9_]{0,40}$/),
  heading: z.string().min(1).max(LIMITS.heading_chars),
  kv: z.array(z.strictObject({ key: z.string().min(1).max(40), value: z.string().min(1).max(LIMITS.kv_value_chars), links })).max(LIMITS.max_kv).optional(),
  items: z.array(z.strictObject({ text: z.string().min(1).max(400), links })).max(LIMITS.max_items).optional(),
  table: z
    .strictObject({
      columns: z.array(z.string().min(1).max(40)).min(2).max(LIMITS.max_cols),
      rows: z.array(z.strictObject({ cells: z.array(z.string().min(1).max(LIMITS.cell_chars)), links })).min(1).max(LIMITS.max_rows),
    })
    .optional(),
});

export const exportInputSchema = z.strictObject({
  client_name: z.string().min(1).max(LIMITS.client_name),
  introduction: z.strictObject({ text: z.string().min(1).max(LIMITS.intro_chars), links }),
  sections: z.array(section).min(0).max(LIMITS.max_sections),
});

/** Visible length of a bullet, including citation labels and the spaces before them. */
export function bulletVisibleLength(item) {
  return item.text.length + (item.links || []).reduce((n, l) => n + 1 + l.label.length, 0);
}

/**
 * Semantic validation beyond the schema. Returns layout_issues-style entries.
 * `isKnownUrl` enforces "only cite URLs actually returned by tools".
 */
export function validateContent(input, { isKnownUrl }) {
  const issues = [];
  const add = (section_id, issue, detail, measured_value, allowed_value) => issues.push({ section_id, issue, detail, measured_value, allowed_value });
  const checkText = (sid, where, text, opts) => {
    const p = visibleProblem(text, opts);
    if (p) add(sid, "disallowed_visible_content", `${where} contains ${p}.`);
  };
  const checkLinks = (sid, where, ls) => {
    for (const l of ls || []) {
      checkText(sid, `${where} link label`, l.label);
      if (/^https?:/i.test(l.label) || /\.[a-z]{2,}\//i.test(l.label)) add(sid, "raw_url_label", `${where} link label looks like a URL.`);
      if (!/^https?:\/\//i.test(l.url)) add(sid, "unsupported_link_scheme", `${where} link must be http(s).`);
      else if (!isKnownUrl(l.url)) add(sid, "uncited_url", `${where} link was not returned by any tool in this session, so it cannot be cited.`);
    }
  };

  checkText("title", "client_name", input.client_name, { allowName: true });
  const words = input.introduction.text.trim().split(/\s+/).length;
  if (words > LIMITS.intro_words) add("introduction", "introduction_too_long", "Introduction must be one or two concise sentences.", words, LIMITS.intro_words);
  const sentences = input.introduction.text.split(/(?<=[.!?])\s+(?=[A-Z0-9“"])/).filter(Boolean).length;
  if (sentences > 2) add("introduction", "introduction_too_long", "Introduction must be at most two sentences.", sentences, 2);
  checkText("introduction", "introduction", input.introduction.text);
  checkLinks("introduction", "introduction", input.introduction.links);

  const seen = new Set();
  for (const s of input.sections) {
    if (seen.has(s.id)) add(s.id, "duplicate_section_id", "Section ids must be unique.");
    seen.add(s.id);
    checkText(s.id, "heading", s.heading);
    const hasBody = (s.kv?.length || 0) + (s.items?.length || 0) + (s.table?.rows.length || 0) > 0;
    if (!hasBody) add(s.id, "empty_section", "Sections must contain at least one row, item or table row; omit empty sections.");
    for (const kv of s.kv || []) {
      checkText(s.id, `kv "${kv.key}" key`, kv.key);
      checkText(s.id, `kv "${kv.key}" value`, kv.value);
      checkLinks(s.id, `kv "${kv.key}"`, kv.links);
    }
    for (const it of s.items || []) {
      checkText(s.id, "item", it.text);
      checkLinks(s.id, "item", it.links);
      const len = bulletVisibleLength(it);
      if (len > LIMITS.bullet_chars) add(s.id, "bullet_too_long", `Bullet is ${len} visible characters including citation labels.`, len, LIMITS.bullet_chars);
    }
    if (s.table) {
      s.table.columns.forEach((c) => {
        checkText(s.id, "table column", c);
        if (/^\s*(confidence|reliability|certainty|rating|credibility)\s*$/i.test(c)) add(s.id, "disallowed_visible_content", `table column "${c}" looks like a confidence or reliability column.`);
      });
      for (const r of s.table.rows) {
        if (r.cells.length !== s.table.columns.length) add(s.id, "ragged_table", `A row has ${r.cells.length} cells but the table has ${s.table.columns.length} columns.`);
        r.cells.forEach((c) => {
          checkText(s.id, "table cell", c);
          if (/^\s*(high|medium|low)\s*$/i.test(c)) add(s.id, "disallowed_visible_content", `table cell "${c.trim()}" looks like a confidence rating.`);
        });
        checkLinks(s.id, "table row", r.links);
      }
    }
  }
  return issues;
}
